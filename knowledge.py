# Τιμές αναφοράς πρόσληψης για ενήλικα (Κανονισμός ΕΕ 1169/2011, Παράρτημα XIII)
RI = {"energy-kcal": (2000, "kcal", "Ενέργεια"), "fat": (70, "g", "Λιπαρά"),
      "saturated-fat": (20, "g", "Κορεσμένα"), "carbohydrates": (260, "g", "Υδατάνθρακες"),
      "sugars": (90, "g", "Σάκχαρα"), "proteins": (50, "g", "Πρωτεΐνες"), "salt": (6, "g", "Αλάτι")}
SUGAR_TSP_G = 4.0          # 1 κουταλάκι του γλυκού ζάχαρη ≈ 4 g
WALK_KCAL_MIN = 4.0        # γρήγορο περπάτημα ≈ 4 kcal/λεπτό (ενήλικας ~70 kg)


def serving_grams(p):
    v = p.get("serving_quantity")
    try:
        v = float(v)
        if v > 0:
            return v
    except (TypeError, ValueError):
        pass
    m = re.search(r"(\d+(?:[.,]\d+)?)\s*(g|ml|γρ)", str(p.get("serving_size") or ""), re.I)
    if m:
        return float(m.group(1).replace(",", "."))
    return None


def _nut(n, key):
    for k in (key + "_100g", key):
        v = n.get(k)
        try:
            if v is not None and v != "":
                return float(v)
        except (TypeError, ValueError):
            continue
    return None


def daily_table(p):
    """[(όνομα, ανά 100 g, % ΗΤ ανά 100 g, ανά μερίδα, % ΗΤ ανά μερίδα, μονάδα)]"""
    n = p.get("nutriments") or {}
    sg = serving_grams(p)
    rows = []
    for key, (ri, unit, label) in RI.items():
        v = _nut(n, key)
        if v is None and key == "energy-kcal":
            kj = _nut(n, "energy")
            v = kj / 4.184 if kj is not None else None
        if v is None and key == "salt":
            na = _nut(n, "sodium")
            v = na * 2.5 if na is not None else None
        if v is None:
            continue
        per = v * sg / 100 if sg else None
        rows.append((label, v, v / ri * 100, per, (per / ri * 100) if per is not None else None, unit))
    return rows, sg


def equivalents(p):
    """Φράσεις όπως «2 κουταλάκια ζάχαρη ανά μερίδα»."""
    n = p.get("nutriments") or {}
    sg = serving_grams(p) or 100
    base = "ανά μερίδα" if serving_grams(p) else "ανά 100 g"
    out = []
    sug = _nut(n, "sugars")
    if sug is not None and sug > 0.5:
        tsp = sug * sg / 100 / SUGAR_TSP_G
        out.append(f"{tsp:.1f} κουταλάκια ζάχαρη {base}".replace(".", ","))
    kcal = _nut(n, "energy-kcal")
    if kcal is None and _nut(n, "energy") is not None:
        kcal = _nut(n, "energy") / 4.184
    if kcal:
        mins = kcal * sg / 100 / WALK_KCAL_MIN
        out.append(f"περίπου {mins:.0f} λεπτά γρήγορο περπάτημα για να «καούν» οι θερμίδες {base}")
    salt = _nut(n, "salt")
    if salt is not None and salt > 0.1:
        out.append(f"{salt * sg / 100 / 6 * 100:.0f}% του μέγιστου αλατιού της ημέρας {base}")
    return out


