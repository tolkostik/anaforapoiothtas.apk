def additive_function(code):
    if code.lower() in FUNCTION_OVERRIDE:
        return FUNCTION_OVERRIDE[code.lower()]
    m = re.match(r"e(\d{3,4})", code.lower())
    if not m:
        return ""
    n = int(m.group(1))
    if 100 <= n < 200:
        return "χρωστική"
    if 200 <= n < 300:
        return "συντηρητικό"
    if 300 <= n < 400:
        return "αντιοξειδωτικό / ρυθμιστής οξύτητας"
    if 400 <= n < 500:
        return "πηκτωματογόνο / γαλακτωματοποιητής / σταθεροποιητής"
    if 500 <= n < 600:
        return "ρυθμιστής οξύτητας / διογκωτικό / αντισυσσωματικό"
    if 600 <= n < 700:
        return "ενισχυτικό γεύσης"
    if 900 <= n < 1000:
        return "γλυκαντικό / επικαλυπτικό / προωθητικό αέριο"
    if n >= 1100:
        return "τροποποιημένο άμυλο / ένζυμο / άλλο"
    return "πρόσθετο"


