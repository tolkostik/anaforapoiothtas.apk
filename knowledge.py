def _is_liquid(p):
    q = str(p.get("quantity") or "").lower()
    cats = " ".join(p.get("categories_tags") or [])
    return bool(re.search(r"\d\s*(ml|cl|l\b|λίτρ)", q)) or "beverages" in cats or "drinks" in cats


def claims(p):
    """Ισχυρισμοί που θα δικαιούνταν το προϊόν με τα επίσημα όρια της ΕΕ: [(κείμενο, θετικό;)].
    Οι αρνητικές ενδείξεις χρησιμοποιούν τα «κόκκινα» όρια της βρετανικής FSA."""
    n = p.get("nutriments") or {}
    liquid = _is_liquid(p)

    def g(k):
        return _nut(n, k)
    kcal = g("energy-kcal")
    if kcal is None and g("energy") is not None:
        kcal = g("energy") / 4.184
    out = []
    sug, fat, sat, salt, fib, pro = g("sugars"), g("fat"), g("saturated-fat"), g("salt"), g("fiber"), g("proteins")
    if sug is not None:
        if sug <= 0.5:
            out.append(("Χωρίς ζάχαρη", True))
        elif sug <= (2.5 if liquid else 5):
            out.append(("Χαμηλά σάκχαρα", True))
    if fat is not None:
        if fat <= 0.5:
            out.append(("Χωρίς λιπαρά", True))
        elif fat <= (1.5 if liquid else 3):
            out.append(("Χαμηλά λιπαρά", True))
    if sat is not None and sat <= (0.75 if liquid else 1.5) and (not kcal or sat * 9 <= 0.1 * kcal):
        out.append(("Χαμηλά κορεσμένα", True))
    if salt is not None:
        if salt <= 0.0125:
            out.append(("Χωρίς αλάτι", True))
        elif salt <= 0.1:
            out.append(("Πολύ χαμηλό αλάτι", True))
        elif salt <= 0.3:
            out.append(("Χαμηλό αλάτι", True))
    if fib is not None:
        if fib >= 6:
            out.append(("Υψηλές φυτικές ίνες", True))
        elif fib >= 3:
            out.append(("Πηγή φυτικών ινών", True))
    if pro is not None and kcal:
        share = pro * 4 / kcal
        if share >= 0.20:
            out.append(("Υψηλή πρωτεΐνη", True))
        elif share >= 0.12:
            out.append(("Πηγή πρωτεΐνης", True))
    if kcal is not None and kcal <= (20 if liquid else 40):
        out.append(("Χαμηλές θερμίδες", True))
    if sug is not None and sug > (11.25 if liquid else 22.5):
        out.append(("Πολλή ζάχαρη", False))
    if salt is not None and salt > (0.75 if liquid else 1.5):
        out.append(("Πολύ αλάτι", False))
    if sat is not None and sat > (2.5 if liquid else 5):
        out.append(("Πολλά κορεσμένα", False))
    return out


