def explain_inci(text):
    """[(συστατικό, εξήγηση)] για τα συστατικά που γνωρίζει το λεξικό, με τη σειρά της ετικέτας."""
    out = []
    for raw in re.split(r"[,;]", text or ""):
        name = raw.strip().strip(".").lower()
        name = re.sub(r"\s*\(.*?\)", "", name).strip()
        if not name:
            continue
        exp = INCI.get(name)
        if exp is None:
            for k, v in INCI.items():
                if len(k) > 6 and k in name:
                    exp = v
                    break
        if exp:
            out.append((raw.strip(), exp))
    seen, uniq = set(), []
    for a, b in out:
        if a.lower() not in seen:
            seen.add(a.lower())
            uniq.append((a, b))
    return uniq


