def recycling(p):
    """[(μέρος, υλικό, πού πάει)] από τα στοιχεία συσκευασίας του Open Food Facts."""
    out = []
    for pk in p.get("packagings") or []:
        mat = str(pk.get("material") or "").lower()
        if not mat:
            continue
        shape = str(pk.get("shape") or "συσκευασία").split(":")[-1].replace("-", " ")
        shape = SHAPES.get(shape, shape)
        key, name = next(((k, v) for k, v in MATERIAL if re.search(r"(^|[:\-])" + k, mat)),
                         (None, mat.split(":")[-1]))
        if key == "glass":
            where = "καμπάνα γυαλιού ή μπλε κάδος"
        elif key == "ps":
            where = "συχνά δεν ανακυκλώνεται: έλεγξε τον δήμο σου"
        elif key == "wood":
            where = "γενικά απορρίμματα"
        else:
            where = "μπλε κάδος ανακύκλωσης"
        out.append((shape, name, where))
    return out
